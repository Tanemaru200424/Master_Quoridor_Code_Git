#!/bin/bash
set -e

N=5
MAX_L=6   # = M。ルール上使えるフェンス総数。
HALF=$((MAX_L / 2))  # 片方のプレイヤーが持てるフェンス数の上限

EXECUTABLE="./quridor_retrograde_NLBW_obj"

# =========================================================
# 解析ファイルを初期化するか
#
# true  : ITER=0 のときに解析対象ファイルを削除して、
#         最初から解析する
#
# false : 既存の解析ファイルをそのまま使用して
#         続きから解析する
# =========================================================
INITIALIZE=true


# =========================================================
# 解析全体での最大手数
#
# 各 (L,B,W) の解析結果に出力される
# "max moves = X"
# の最大値を保持する。
#
# ITERが変わってもリセットしない。
# =========================================================
MAX_MOVES=0


# =========================================================
# 1 ITER分の全組合せを解析する
#
# 引数:
#   $1 = ITER
#
# 戻り値:
#   0 : 全組合せが終了条件を満たした
#   1 : 1つでも終了条件を満たしていない
# =========================================================
run_iteration() {

    local ITER=$1

    # -----------------------------------------------------
    # このITERで全組合せが終了条件を満たしたか
    #
    # 最初は「全て終了」と仮定する。
    # 1つでも未終了なら false にする。
    # -----------------------------------------------------
    local ALL_FINISHED=true


    echo ""
    echo "########################################################"
    echo "### ITER=${ITER} 開始"
    echo "########################################################"


    # =====================================================
    # LをMAX_Lから0まで降順に処理
    # =====================================================
    for (( L=MAX_L; L>=0; L-- )); do


        # =================================================
        # Bを0からHALFまで処理
        # =================================================
        for (( B=0; B<=HALF; B++ )); do

            W=$(( MAX_L - L - B ))


            # -------------------------------------------------
            # Wが範囲外なら、この組合せは存在しない
            # -------------------------------------------------
            if (( W < 0 || W > HALF )); then
                continue
            fi


            echo ""
            echo "=========================================="
            echo "=== L=${L} B=${B} W=${W} ITER=${ITER} ==="
            echo "=========================================="


            # =================================================
            # ヘッダーを書き換え
            # =================================================

            # zdd_quoridor_board_only.hpp の N, L
            sed -i \
                "s/static constexpr int N = [0-9]*;/static constexpr int N = ${N};/" \
                zdd_quoridor_board_only.hpp

            sed -i \
                "s/static constexpr int L = [0-9]*;/static constexpr int L = ${L};/" \
                zdd_quoridor_board_only.hpp


            # main_quoridor_retrograde_NLBW.cpp の B, W
            sed -i \
                "s/static constexpr int B = [0-9]*;/static constexpr int B = ${B};/" \
                main_quoridor_retrograde_NLBW.cpp

            sed -i \
                "s/static constexpr int W = [0-9]*;/static constexpr int W = ${W};/" \
                main_quoridor_retrograde_NLBW.cpp


            # =================================================
            # コンパイル
            # =================================================

            echo "--- コンパイル開始 (L=${L} B=${B} W=${W}) ---"

            g++ -std=c++11 \
                main_quoridor_retrograde_NLBW.cpp \
                zdd_quoridor_board_only.cpp \
                posi_quoridor_board_only.cpp \
                -o "$EXECUTABLE" \
                -pthread

            echo "--- コンパイル成功 ---"


            # =================================================
            # ファイル名を決定
            # =================================================

            LBW="quoridor_gamevalue_N${N}L${L}B${B}W${W}.bin"

            LWB="quoridor_gamevalue_N${N}L${L}B${W}W${B}.bin"


            # -------------------------------------------------
            # L+1, W/B入れ替え側のファイル
            # -------------------------------------------------

            if [ "$B" -gt 0 ]; then

                LP1WBM1="quoridor_gamevalue_N${N}L$((L+1))B${W}W$((B-1)).bin"

            else

                LP1WBM1="NULL"

            fi


            if [ "$W" -gt 0 ]; then

                LP1BWM1="quoridor_gamevalue_N${N}L$((L+1))B${B}W$((W-1)).bin"

            else

                LP1BWM1="NULL"

            fi


            # =================================================
            # ITER=0 かつ INITIALIZE=true の場合のみ
            # 解析対象ファイルを初期化
            # =================================================

            if [ "$ITER" -eq 0 ] && [ "$INITIALIZE" = true ]; then

                echo "--- 解析対象ファイルを初期化します ---"

                echo "削除: $LBW"
                rm -f "$LBW"

                echo "削除: $LWB"
                rm -f "$LWB"


            elif [ "$ITER" -eq 0 ]; then

                echo "--- 既存の解析対象ファイルを使用します ---"

                if [ -f "$LBW" ]; then

                    echo "既存ファイル: $LBW"

                else

                    echo "ファイルなし: $LBW"

                fi


                if [ -f "$LWB" ]; then

                    echo "既存ファイル: $LWB"

                else

                    echo "ファイルなし: $LWB"

                fi

            fi


            # =================================================
            # この組合せを現在のITERで1回解析
            # =================================================

            echo ""
            echo "実行コマンドライン"

            echo "${EXECUTABLE} ${N} ${L} ${B} ${W} ${ITER} ${LBW} ${LWB} ${LP1WBM1} ${LP1BWM1}"


            OUTPUT=$(
                "$EXECUTABLE" \
                "$N" \
                "$L" \
                "$B" \
                "$W" \
                "$ITER" \
                "$LBW" \
                "$LWB" \
                "$LP1WBM1" \
                "$LP1BWM1"
            )


            # =================================================
            # 実行結果を表示
            # =================================================

            echo "実行結果"
            echo "$OUTPUT"
            echo "--------------------------"


            # =================================================
            # max movesを取得
            #
            # C++側の出力:
            #
            # max moves = X
            #
            # からXを取得する。
            # =================================================

            CURRENT_MAX_MOVES=$(
                echo "$OUTPUT" |
                grep '^max moves = ' |
                awk '{print $4}'
            )


            # -------------------------------------------------
            # max movesが正常に取得できた場合
            # 解析全体の最大値を更新する
            # -------------------------------------------------

            if [ -n "$CURRENT_MAX_MOVES" ]; then

                if [ "$CURRENT_MAX_MOVES" -gt "$MAX_MOVES" ]; then

                    MAX_MOVES=$CURRENT_MAX_MOVES

                fi

            fi


            echo "今回の解析のMaxMoves = ${CURRENT_MAX_MOVES:-取得失敗}"
            echo "解析全体の現在のMaxMoves = ${MAX_MOVES}"


            # =================================================
            # 最後の2行を取得
            #
            # 例:
            #
            # 4
            # 0
            #
            # LAST_LINE_1 = total new value count
            # LAST_LINE_2 = leave unknown count
            # =================================================

            LAST_LINE_1=$(echo "$OUTPUT" | tail -n 2 | head -n 1)

            LAST_LINE_2=$(echo "$OUTPUT" | tail -n 1)


            # =================================================
            # 終了条件判定
            #
            # 終了条件:
            #
            #   ITER > 0
            #   かつ
            #   total new value count == 0
            #
            # ITER=0では新しい値が0でも終了しない。
            # =================================================

            if [[ "$ITER" -gt 0 && "$LAST_LINE_1" == "0" ]]; then

                echo "total new value count = 0"
                echo "→ L=${L} B=${B} W=${W} は終了条件達成"


            else

                echo "total new value count = ${LAST_LINE_1}"
                echo "→ L=${L} B=${B} W=${W} は終了条件未達成"

                # -------------------------------------------------
                # 重要:
                #
                # ここではbreakしない。
                #
                # このITERの残りの全組合せも必ず実行する。
                # -------------------------------------------------

                ALL_FINISHED=false

            fi

        done

    done


    # =====================================================
    # 全組合せの解析が完了した後に判定
    #
    # 途中で未達成の組合せがあっても、
    # 全組合せの処理が終わるまでは次のITERへ進まない。
    # =====================================================

    if [ "$ALL_FINISHED" = true ]; then

        echo ""
        echo "########################################################"
        echo "### ITER=${ITER} で全組合せが終了条件を満たしました"
        echo "########################################################"

        return 0


    else

        echo ""
        echo "########################################################"
        echo "### ITER=${ITER} で未終了の組合せがあります"
        echo "### 次のITERへ進みます"
        echo "########################################################"

        return 1

    fi
}


# =========================================================
# ITERループ
#
# ITER=0から開始し、
# 全組合せが終了条件を満たすまで増加させる。
# =========================================================

ITER=0


while true; do

    # -----------------------------------------------------
    # 現在のITERで全組合せを必ず実行
    # -----------------------------------------------------

    if run_iteration "$ITER"; then

        # -------------------------------------------------
        # 全組合せ終了
        # -------------------------------------------------

        break

    fi


    # -----------------------------------------------------
    # 1つでも未終了なら次のITERへ
    # -----------------------------------------------------

    ITER=$((ITER + 1))

done


# =========================================================
# 全解析終了
# =========================================================

echo ""
echo "========================================================"
echo "全ての(L,B,W)組合せの解析が終了しました。"
echo "最終ITER=${ITER}"
echo "解析全体のMaxMoves=${MAX_MOVES}"
echo "========================================================"